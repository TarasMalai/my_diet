import 'package:flutter/material.dart';

// ----------------------------------------------------------------------------
// [ВУЗОЛ 1]: СЕРВІС УПРАВЛІННЯ ДАТОЮ (DateService)
// ----------------------------------------------------------------------------
class DateService {
  // --------------------------------------------------------------------------
  // [ВУЗОЛ 1.1]: РЕАЛІЗАЦІЯ ПАТЕРНУ SINGLETON (Одинак)
  // --------------------------------------------------------------------------
  static final DateService _instance = DateService._internal();
  factory DateService() => _instance;
  DateService._internal();

  // --------------------------------------------------------------------------
  // [ВУЗОЛ 1.2]: РЕАКТИВНА ЗМІННА ОБРАНОЇ ДАТИ (selectedDate)
  // --------------------------------------------------------------------------
  /// При старті програми автоматично встановлює DateTime.now()
  final ValueNotifier<DateTime> selectedDate = ValueNotifier<DateTime>(DateTime.now());

  // --------------------------------------------------------------------------
  // [ВУЗОЛ 1.3]: МЕТОД ОНОВЛЕННЯ ДАТИ (updateDate)
  // --------------------------------------------------------------------------
  /// Оновлює обрану дату для всього додатку з будь-якого екрана
  void updateDate(DateTime newDate) {
    selectedDate.value = newDate;
  }
}
