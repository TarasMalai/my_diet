import 'package:flutter/material.dart';

// ----------------------------------------------------------------------------
// [ВУЗОЛ 1]: ЕНУМЕРАТОР ПРІОРИТЕТУ НОТАТКИ (NotePriority)
// ----------------------------------------------------------------------------
enum NotePriority { low, medium, high } // Зелений, Жовтий, Червоний

// ----------------------------------------------------------------------------
// [ВУЗОЛ 2]: МОДЕЛЬ СІМЕЙНОЇ НОТАТКИ (FamilyNote)
// ----------------------------------------------------------------------------
class FamilyNote {
  // --------------------------------------------------------------------------
  // [ВУЗОЛ 2.1]: ПОЛЯ МОДЕЛІ (Властивості нотатки)
  // --------------------------------------------------------------------------
  final String id;
  final String authorName;
  final String content;
  final NotePriority priority;
  final DateTime timestamp;
  final String? attachmentPath; // Універсальний шлях до файлу (JPG або PDF)
  final bool isImage; // Прапорець для швидкої перевірки типу вкладення

  // --------------------------------------------------------------------------
  // [ВУЗОЛ 2.2]: ГОЛОВНИЙ КОНСТРУКТОР
  // --------------------------------------------------------------------------
  FamilyNote({
    required this.id,
    required this.authorName,
    required this.content,
    required this.priority,
    required this.timestamp,
    this.attachmentPath,
    this.isImage = false,
  });

  // --------------------------------------------------------------------------
  // [ВУЗОЛ 2.3]: ГЕТТЕР КОЛЬОРУ ПРІОРИТЕТУ (priorityColor)
  // --------------------------------------------------------------------------
  Color get priorityColor {
    switch (priority) {
      case NotePriority.low:
        return Colors.green.shade400;
      case NotePriority.medium:
        return Colors.amber.shade600;
      case NotePriority.high:
        return Colors.red.shade600;
    }
  }
}
