import 'package:flutter/material.dart';

// ----------------------------------------------------------------------------
// [ВУЗОЛ 1]: ЕНУМЕРАТОР ТИПІВ НУТРІЄНТІВ (NutrientType)
// ----------------------------------------------------------------------------
enum NutrientType { fa, calories, protein, water, carbs, fats }

// ----------------------------------------------------------------------------
// [ВУЗОЛ 2]: МОДЕЛЬ КОНФІГУРАЦІЇ НУТРІЄНТА (NutrientConfig)
// ----------------------------------------------------------------------------
class NutrientConfig {
  // --------------------------------------------------------------------------
  // [ВУЗОЛ 2.1]: ПОЛЯ МОДЕЛІ (Властивості нутрієнта)
  // --------------------------------------------------------------------------
  final NutrientType type;
  final String label;
  final String unit;
  final Color color;
  final IconData icon;

  // --------------------------------------------------------------------------
  // [ВУЗОЛ 2.2]: ГОЛОВНИЙ КОНСТРУКТОР
  // --------------------------------------------------------------------------
  const NutrientConfig({
    required this.type,
    required this.label,
    required this.unit,
    required this.color,
    required this.icon,
  });

  // --------------------------------------------------------------------------
  // [ВУЗОЛ 2.3]: КОПІЮВАННЯ ОБ'ЄКТА З ЗМІНАМИ (copyWith)
  // --------------------------------------------------------------------------
  NutrientConfig copyWith({NutrientType? type, String? label, String? unit, Color? color, IconData? icon}) {
    return NutrientConfig(
      type: type ?? this.type,
      label: label ?? this.label,
      unit: unit ?? this.unit,
      color: color ?? this.color,
      icon: icon ?? this.icon,
    );
  }
}
