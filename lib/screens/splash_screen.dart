// ============================================================================
// НАЗВА ФАЙЛУ: splash_screen.dart
// ПРОЄКТ: Моя дієта
// ПРИЗНАЧЕННЯ: Екран заставки (Splash Screen). Показує логотип програми та
//              анімацію завантаження (крутілку), після чого через 3 секунди
//              автоматично перенаправляє користувача на головний екран.
// ============================================================================

import 'dart:async'; // 1.1. Потрібно для роботи таймера затримки (Timer)
import 'package:flutter/material.dart';
import 'package:my_diet/screens/main_screen.dart'; // 1.2. Імпортуємо головний екран для подальшого переходу

// ----------------------------------------------------------------------------
// 1. КЛАС СТАНУ ЗАСТАВКИ (SplashScreen)
// ----------------------------------------------------------------------------
/// Оскільки заставка містить динамічний таймер, використовуємо StatefulWidget.
/// [ВУЗОЛ 1.1: StatefulWidget]
/// Використовується тоді, коли віджет повинен відстежувати зміни або виконувати
/// внутрішню логіку під час свого життєвого циклу (наприклад, асинхронні таймери,
/// анімації чи оновлення даних).
class SplashScreen extends StatefulWidget {
  const SplashScreen({super.key});

  @override
  State<SplashScreen> createState() => _SplashScreenState();
}

// ----------------------------------------------------------------------------
// 2. ЛОГІКА ТА ВІЗУАЛЬНЕ ОФОРМЛЕННЯ ( _SplashScreenState )
// ----------------------------------------------------------------------------
class _SplashScreenState extends State<SplashScreen> {
  // --------------------------------------------------------------------------
  // ВУЗОЛ 2.1: ІНІЦІАЛІЗАЦІЯ ТА АВТОМАТИЧНИЙ ТАЙМЕР
  // --------------------------------------------------------------------------
  /// Метод спрацьовує один раз одразу після появи заставки на екрані.
  /// [ВУЗОЛ 2.1.1:initState]
  /// Викликається автоматично при створенні об'єкта стану State.
  /// Ідеальне місце для підписки на події, запуску таймерів або первинного завантаження даних.
  @override
  void initState() {
    super.initState();

    // Запускаємо таймер зворотного відліку на 3 секунди
    // [ВУЗОЛ 2.1.2: Timer]
    // Асинхронний таймер із бібліотеки 'dart:async'. Виконує анонімну функцію () {}
    // після закінчення вказаної тривалості (3 секунди).
    Timer(const Duration(seconds: 3), () {
      // Захисна перевірка: чи існує ще віджет на екрані, щоб уникнути помилок
      // [ВУЗОЛ 2.1.3: mounted]
      // Геттер mounted повертає true, якщо віджет досі перебуває у дереві елементів.
      // Захищає від виклику Navigator/setState, якщо користувач закрив екран до завершення таймера.
      if (!mounted) return;

      // Повністю замінюємо заставку на MainScreen (користувач не зможе повернутися назад)
      // [ВУЗОЛ 2.1.4: Navigator.pushReplacement]
      // Видаляє поточний екран зі стеку навігації та ставить на його місце новий.
      // Натискання системної кнопки "Назад" не поверне користувача на екран заставки.
      Navigator.of(context).pushReplacement(MaterialPageRoute(builder: (context) => const MainScreen()));
    });
  }

  // --------------------------------------------------------------------------
  // ВУЗОЛ 2.2: ВІЗУАЛЬНИЙ КАРКАС (BUILD)
  // --------------------------------------------------------------------------
  @override
  Widget build(BuildContext context) {
    return const Scaffold(
      // Задаємо фірмовий зелений фон для заставки
      backgroundColor: Colors.green,

      body: Center(
        child: Column(
          // Центруємо весь вміст по вертикалі
          // [ВУЗОЛ 2.2.1: MainAxisAlignment]
          // Вирівнює всі дочірні віджети Column по центру відносно вертикальної осі.
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            // 2.2.1. Головний текстовий логотип програми
            Text(
              'Моя дієта',
              style: TextStyle(fontSize: 40, fontWeight: FontWeight.bold, color: Colors.white, letterSpacing: 1.2),
            ),

            // 2.2.2. Відступ між назвою та підзаголовком
            SizedBox(height: 8),

            // 2.2.3. Підзаголовок додатка
            Text('Ваш персональний помічник', style: TextStyle(fontSize: 16, color: Colors.white70)),

            // 2.2.4. Відступ перед індикатором завантаження
            SizedBox(height: 40),

            // 2.2.5. Круговий індикатор завантаження (крутілка) білого кольору
            // [ВУЗОЛ 2.2.2: CircularProgressIndicator]
            // Нативний Material-індикатор завантаження. AlwaysStoppedAnimation перевизначає
            // колір анімації на суцільний білий.
            CircularProgressIndicator(valueColor: AlwaysStoppedAnimation<Color>(Colors.white)),
          ],
        ),
      ),
    );
  }
}
