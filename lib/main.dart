import 'package:flutter/material.dart';
// 1. Імпортуємо ініціалізатор локалей для пакета intl
import 'package:intl/date_symbol_data_local.dart';
import 'package:my_diet/screens/splash_screen.dart'; // Імпортуємо екран заставки, з якого стартуємо

// ----------------------------------------------------------------------------
// 1. ТОЧКА ВХОДУ (Функція main)
// ----------------------------------------------------------------------------
/// Це перша функція, яка виконується при запуску програми на пристрої.
/// Модифікатор `async` дозволяє використовувати асинхронний виклик `await` всередині.
void main() async {
  // [ВУЗОЛ 1.1: Зв'язок з двигуном Flutter]
  // Обов'язково ініціалізуємо зв'язки Flutter перед викликом сторонніх асинхронних пакетів.
  // Без цього виклик initializeDateFormatting викличе помилку, оскільки плагіни
  // ще не прив'язані до нативного коду (Android/iOS).
  WidgetsFlutterBinding.ensureInitialized();

  // 2. Ініціалізуємо українську локаль 'uk_UA' для коректного форматування дат
  // Ключове слово `await` призупиняє виконання main(), поки локалізація не завантажиться повністю.
  await initializeDateFormatting('uk_UA', null);

  // Запуск root-віджета нашого додатка
  runApp(const MyDietApp());
}

// ----------------------------------------------------------------------------
// 2. ГОЛОВНИЙ КЛАС ДОДАТКУ (MyDietApp)
// ----------------------------------------------------------------------------
/// Відповідає за загальну конфігурацію додатку (MaterialApp).
/// Наслідується від StatelessWidget, оскільки глобальні конфігурації теми та роутингу
/// не потребують власного внутрішнього стану на цьому рівні.
class MyDietApp extends StatelessWidget {
  // [ВУЗОЛ 2.1: Конструктор з супер-ключем]
  // {super.key} передає ключ віджета батьківському класу StatelessWidget для
  // оптимізації відтворення дерева елементів Flutter.
  const MyDietApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      // Загальна назва додатку в системі (відображається в меню запущених додатків)
      title: 'Моя дієта',

      // Вимикаємо плашку "DEBUG" у правому верхньому кутку екрана
      debugShowCheckedModeBanner: false,

      // Глобальна тема оформлення додатку (зелена палітра)
      // [ВУЗОЛ 2.2: Тематизація Material 3]
      // ColorScheme.fromSeed автоматично генерує збалансовану колірну гаму на основі базового кольору.
      theme: ThemeData(colorScheme: ColorScheme.fromSeed(seedColor: Colors.green), useMaterial3: true),

      // 3. СТАРТОВИЙ ЕКРАН
      // Вказуємо, що при запуску першим з'являється SplashScreen (заставка)
      home: const SplashScreen(),
    );
  }
}
